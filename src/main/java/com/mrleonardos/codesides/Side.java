package com.mrleonardos.codesides;

/**
 * Физическая сторона сборки, на которую попадает помеченный код.
 *
 * <p>Не путать с {@code cpw.mods.fml.relauncher.Side}: то рантайм-понятие (FML вырезает
 * {@code @SideOnly} при ЗАГРУЗКЕ класса, оставляя байткод в jar). Здесь понятие СБОРКИ: помеченный
 * элемент физически удаляется из чужого jar ещё на этапе сборки, поэтому его нельзя декомпилировать
 * из чужой стороны.
 */
public enum Side
{
	/** Только серверный jar. Вырезается из клиентского. */
	SERVER,
	/** Только клиентский jar. Вырезается из серверного. */
	CLIENT;

	/** Противоположная сторона: та, из чьего jar помеченный этой стороной код вырезается. */
	public Side opposite()
	{
		return this == SERVER ? CLIENT : SERVER;
	}
}
